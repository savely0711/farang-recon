"""Отпечаток фотографии (dHash) — для поиска дублей на сайте.

ЗАЧЕМ. Один и тот же снимок, прошедший через Telegram, пережатый и уменьшенный,
байт в байт уже не совпадает — сравнивать файлы бесполезно. Отпечаток описывает
саму картинку: 64 бита, которые почти не меняются от пережатия, но полностью
различаются у разных фотографий. Сайт хранит их в listing_photos.phash (db/33)
и по ним показывает модератору пары «похоже на дубль».

КАК СЧИТАЕМ. Ровно так же, как браузер сайта в src/lib/phash.ts — иначе
отпечатки одной и той же картинки не сойдутся:

  1) уменьшаем до 144x128 обычными средствами;
  2) переводим в градации серого и честно усредняем блоками 16x16 — получается
     сетка 9x8. Второй шаг и делает результат независимым от способа
     уменьшения: без него Pillow и браузер расходятся на 6-8 бит из 64, то есть
     ровно на величину, по которой мы отличаем дубль от не-дубля (проверено);
  3) в каждой строке сравниваем соседние клетки: левая светлее правой — 1,
     иначе 0. Восемь строк по восемь сравнений = 64 бита.

Наружу отдаём строку из 64 нулей и единиц — в таком виде её принимает сайт.
"""
from __future__ import annotations

import io

W, H, CELL = 144, 128, 16   # 144/16 = 9 клеток по ширине, 128/16 = 8 по высоте


def fingerprint(raw: bytes) -> str | None:
    """Отпечаток картинки из байтов файла. None — картинку не разобрать."""
    try:
        from PIL import Image  # noqa: PLC0415 — необязательная зависимость
    except ImportError:
        return None

    try:
        img = Image.open(io.BytesIO(raw)).convert("L").resize((W, H))
    except Exception:  # noqa: BLE001
        return None

    px = img.load()
    if px is None:
        return None

    cells = [0.0] * (9 * 8)
    for y in range(H):
        row = (y // CELL) * 9
        for x in range(W):
            cells[row + x // CELL] += px[x, y]
    area = CELL * CELL
    cells = [c / area for c in cells]

    bits = []
    for y in range(8):
        for x in range(8):
            bits.append("1" if cells[y * 9 + x] > cells[y * 9 + x + 1] else "0")
    return "".join(bits)


def distance(a: str, b: str) -> int:
    """Насколько отпечатки различаются: 0-4 «то же фото», больше 8 — разные."""
    if not a or not b or len(a) != len(b):
        return 64
    return sum(1 for x, y in zip(a, b) if x != y)
