"""
Проверка контура недвижимости (разбор правилами + сборка строки таблицы).
Ничего не пишет в Google и не ходит в сеть. Запуск: python3 test_realty.py

Тексты в тестах — типовые формулировки из групп аренды Паттайи: с эмодзи,
кривыми пробелами, депозитами, телефонами и ценами в трёх видах записи.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

FAILED = []


def check(name, cond, extra=""):
    if cond:
        print(f"  ✅ {name}")
    else:
        FAILED.append(name)
        print(f"  ❌ {name}" + (f"\n       {extra}" if extra else ""))


def eq(name, got, want):
    check(f"{name}: {want}", got == want, f"получили {got!r}, ждали {want!r}")


from realty_extract import extract, is_realty_candidate  # noqa: E402

# ─────────────── 1. Аренда, простая строка ───────────────
print("\n1. Аренда студии с депозитом")
r = extract("Сдам студию в Джомтьене, 12 000 бат/мес, 30 кв.м, бассейн, "
            "тренажёрка. Депозит 24 000 бат.")
eq("это недвижимость", r["is_realty"], True)
eq("сделка", r["deal"], "аренда")
eq("тип", r["prop_type"], "студия")
eq("цена", r["price"], 12000)
eq("залог не стал ценой", r["price_max"], None)
eq("период", r["period"], "месяц")
eq("спальни (студия = 0)", r["bedrooms"], 0)
eq("площадь", r["area"], 30.0)
eq("район", r["district"], "Джомтьен")
eq("предложение", r["kind"], "предложение")

# ─────────────── 2. Продажа в миллионах ───────────────
print("\n2. Продажа кондо, цена в млн, район из названия проекта")
r = extract("Продаю кондо Riviera Wongamat, 1 спальня, 35 м², 4.5 млн бат. "
            "Вид на море, 12 этаж.")
eq("сделка", r["deal"], "продажа")
eq("тип", r["prop_type"], "кондо")
eq("цена", r["price"], 4_500_000)
eq("период", r["period"], "всего")
eq("спальни", r["bedrooms"], 1)
eq("площадь", r["area"], 35.0)
eq("район по проекту", r["district"], "Вонгамат")

# ─────────────── 3. Английский пост ───────────────
print("\n3. Английский пост")
r = extract("For rent condo Centric Sea, 2BR, 55 sqm, 28,000 THB/month, "
            "pool view, ready to move in")
eq("сделка", r["deal"], "аренда")
eq("цена", r["price"], 28000)
eq("период", r["period"], "месяц")
eq("спальни", r["bedrooms"], 2)
eq("площадь", r["area"], 55.0)
eq("район по проекту", r["district"], "Центр Паттайи")

# ─────────────── 4. Спрос ───────────────
print("\n4. Спрос (сниму) — записываем, но в счётчик агентств не идёт")
r = extract("Сниму квартиру в Паттайе до 15000 бат в месяц, надолго, "
            "семья без животных, без депозита желательно")
eq("это недвижимость", r["is_realty"], True)
eq("спрос", r["kind"], "спрос")
r2 = extract("Ищете квартиру в аренду? Поможем подобрать! Более 500 объектов, "
             "комиссии нет. Пишите в личку.")
eq("«ищете» у агентства — это предложение", r2["kind"], "предложение")

# ─────────────── 5. Не недвижимость ───────────────
print("\n5. Посторонние посты")
r = extract("Продам диван и холодильник, самовывоз из дома, 5000 бат за всё")
eq("мебель — не недвижимость", r["is_realty"], False)
check("короткая болтовня даже не разбирается", not is_realty_candidate("Актуально?"))
check("объявление проходит предфильтр",
      is_realty_candidate("Сдается кондо на Пратамнаке, 1 спальня, 18000 бат"))

# ─────────────── 6. Цена без слова «сдам» ───────────────
print("\n6. Сделку не назвали, но цена за месяц")
r = extract("Дом с бассейном в Хуай Яй, 3 спальни, 45,000 бат/месяц. "
            "Депозит 90,000 бат.")
eq("аренда угадана по «за месяц»", r["deal"], "аренда")
eq("цена, а не залог", r["price"], 45000)
eq("тип", r["prop_type"], "дом")
eq("район", r["district"], "Хуай Яй")

# ─────────────── 7. Телефон в тексте ───────────────
print("\n7. Телефон не должен стать ценой")
r = extract("Сдам студию 13000 бат/мес, Наклуа. Тел +66 81 234 5678, "
            "звоните после 10:00")
eq("цена", r["price"], 13000)
eq("район", r["district"], "Наклуа")

# ─────────────── 8. Сокращённая запись цены ───────────────
print("\n8. Цена сокращением и с ฿")
eq("18к бат", extract("Сдам кондо 18к бат в месяц, Джомтьен")["price"], 18000)
eq("21 000฿/мес", extract("🔥АРЕНДА🔥 Кондо The Base, студия, 21 000฿/мес")["price"], 21000)
eq("3.5 млн", extract("Продам квартиру 3.5 млн бат, Пратамнак")["price"], 3_500_000)
eq("1,250,000 THB",
   extract("Продажа студии на Пратамнаке, 26 кв м. Цена 1,250,000 THB")["price"], 1_250_000)

# ─────────────── 9. Диапазон ───────────────
print("\n9. Диапазон цен")
r = extract("Сдаются студии и однокомнатные в Центральной Паттайе, "
            "от 15 000 до 25 000 бат в месяц")
eq("низ диапазона", r["price"], 15000)
eq("верх диапазона", r["price_max"], 25000)

# ─────────────── 10. Посуточно и тайский ───────────────
print("\n10. Посуточно и тайский текст")
r = extract("Сдается вилла Bang Saray, 4 спальни, посуточно 8500 бат, "
            "бассейн, до моря 300 м")
eq("период", r["period"], "сутки")
eq("цена", r["price"], 8500)
eq("тип", r["prop_type"], "вилла")
eq("район", r["district"], "Банг Сарай")
r = extract("ให้เช่า คอนโด 1 ห้องนอน 15,000 บาท/เดือน จอมเทียน")
eq("тайский: сделка", r["deal"], "аренда")
eq("тайский: цена", r["price"], 15000)
eq("тайский: спальни", r["bedrooms"], 1)
eq("тайский: район", r["district"], "Джомтьен")

# ─────────────── 11. Строка для таблицы ───────────────
print("\n11. Сборка строки для таблицы (realty_sheets.py)")
os.environ.setdefault("REALTY_SHEET_WEBHOOK_URL", "https://example.invalid/exec")
from datetime import datetime, timezone  # noqa: E402

import realty_sheets  # noqa: E402

row = realty_sheets.RealtySheet._row({
    "author": "@AgencyPattaya",
    "link": "https://t.me/baraholka_pattaya/12345",
    "channel": "Барахолка Паттайя Недвижимость",
    "date": datetime(2026, 8, 25, 9, 30, tzinfo=timezone.utc),
    "snippet": "Сдам студию в Джомтьене, 12 000 бат/мес",
    "fields": extract("Сдам студию в Джомтьене, 12 000 бат/мес, 30 кв.м"),
})
eq("ник без @ и в нижнем регистре", row["author"], "agencypattaya")
eq("дата строкой", row["date"], "2026-08-25 09:30")
eq("цена в строке", row["price"], 12000)
eq("район в строке", row["district"], "Джомтьен")
check("описание не пустое", bool(row["snippet"]))

# ─────────────── 12. Свои файлы памяти ───────────────
print("\n12. Контур недвижимости не мешает старой разведке")
import realty_parser  # noqa: E402

check("своя память прочитанного (realty_state.json)",
      realty_parser.state.STATE_FILE.endswith("realty_state.json"),
      realty_parser.state.STATE_FILE)
check("свой список повторов (realty_dedup.json)",
      realty_parser.dedup.DEDUP_FILE.endswith("realty_dedup.json"),
      realty_parser.dedup.DEDUP_FILE)
check("рассылка не подключена", not hasattr(realty_parser, "outreach_queue"))

# ─────────────── итог ───────────────
print("\n" + "=" * 60)
if FAILED:
    print(f"❌ провалено проверок: {len(FAILED)}")
    for name in FAILED:
        print("   -", name)
    sys.exit(1)
print("✅ Все проверки пройдены.")
